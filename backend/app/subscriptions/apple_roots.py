def apple_root_certificates() -> list[bytes]:
    """Return verified DER roots accepted by Apple's official server library."""
    certificates = [b64decode(_APPLE_ROOT_CA_G2), b64decode(_APPLE_ROOT_CA_G3)]
    if tuple(sha256(item).hexdigest() for item in certificates) != _EXPECTED_DIGESTS:
        raise RuntimeError("apple_root_certificate_integrity_failed")
    return certificates
